export const adminTranslations = { id, en }

export function translateAdminText(language, key, params = {}) {
  const lang = String(language || '').toLowerCase().startsWith('en') ? 'en' : 'id'
  const template = adminTranslations[lang][key] ?? adminTranslations.id[key] ?? key
  return String(template).replace(/\{([\w]+)\}/g, (match, name) => {
    const value = params[name]
    return value === undefined || value === null ? match : String(value)
  })
}
